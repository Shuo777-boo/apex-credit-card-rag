import { ConfigProvider } from 'antd';
import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import EvaluationJobs from '../src/EvaluationJobs';
import { api } from '../src/api';
import type { EvaluationOptions, EvaluationJob, JobEstimate } from '../src/types';
const estimate:JobEstimate={configurations:[{build_id:'a'.repeat(24),mode:'dense',strategy:'fixed_window'}],total_questions:30,logical_calls_max:30,http_attempts_max:90,cost_ceiling_cny:3,conservative_estimate_cny:.01,retries_max:2,candidate_depth:100,rerank_depth:100,top_k:20,query_cache:false,prices_cny_per_million:{embedding:.5},caveats:['TEST ONLY']};
